import type { PermissionKey } from "./permission-registry";
import type { Role } from "./role.types";
import type { ScopeType } from "./scope.types";

/**
 * Contract metadata for all 209 HTTP operations frozen by API Contract v1.1
 * ("Master Endpoint Registry": 203 from v1.0 + 6 protected Admin read
 * operations added in v1.1). Transcribed operation-by-operation from the
 * source document.
 *
 * THIS IS CONTRACT METADATA ONLY. It does not implement resource-scope
 * checks in Wave 0D-2 -- no controller currently reads this file at
 * request time. It exists so that (a) the 209-operation authorization
 * surface is fully accounted for before any guard work proceeds, per the
 * Wave 0D-2 mandate, and (b) later waves (0D-3 resource-scope evaluators,
 * 0D-5 non-disclosure hardening, 0D-6 workflow enforcement) have a single
 * source to wire real controllers against instead of re-deriving mappings
 * ad hoc from the docx.
 *
 * Every one of the 209 operations has an authoritative PUBLIC /
 * AUTHENTICATED_ONLY / PERMISSION_PROTECTED disposition (Wave 0D-2 Closure
 * Pass). The 5 operations that were AMBIGUOUS after the initial Wave 0D-2
 * transcription (API-DON-001/002/003, API-FILE-001/002) were resolved by
 * re-reading API Contract v1.1's exact rows plus RBAC v1.0, SRS v2.0, the
 * Use Case Specification, and System Architecture v1.2 -- see each
 * resolved entry's `note` field and the Wave 0D-2 Closure Report for full
 * citations. No RBAC permission key was invented to force a resolution:
 * where the contract genuinely delegates authorization to the calling
 * domain (API-FILE-001/002), that is represented explicitly via
 * `authorizationMode: "CALLER_DOMAIN_PERMISSION"` rather than a fake fixed
 * permissionKey.
 */
export type RouteClassification = "PUBLIC" | "AUTHENTICATED_ONLY" | "PERMISSION_PROTECTED";

/**
 * DIRECT_PERMISSION (the default, all but 2 of the 209 operations): the
 * operation's authorization is fully described by this row's own
 * permissionKey/scope.
 *
 * CALLER_DOMAIN_PERMISSION (API-FILE-001 and API-FILE-002 only, per API
 * Contract v1.1's explicit "Caller domain permission" wording): this is a
 * generic, cross-domain infrastructure operation with no single fixed RBAC
 * key -- the real permission and resource-context check must be resolved
 * from whichever parent domain resource the file belongs to (e.g. a
 * portfolio evidence upload is governed by portfolio.manage_own[OWN], a
 * report attachment by report.prepare_review_assigned[ASG]). A
 * CALLER_DOMAIN_PERMISSION operation is always PERMISSION_PROTECTED, never
 * AUTHENTICATED_ONLY, and must never be role/session-only allowed: missing
 * caller-domain authorization context is a DENY, and so is any attempt to
 * call it without a resolvable parent-domain permission. This is a narrow,
 * explicitly typed exception restricted to exactly these 2 API IDs (see
 * api-authorization-map.spec.ts's allow-list test) -- permissionKey is not
 * generally optional for PERMISSION_PROTECTED operations.
 */
export type AuthorizationMode = "DIRECT_PERMISSION" | "CALLER_DOMAIN_PERMISSION";

/**
 * Set only for API-DON-003 (the Stripe webhook). Authorization for this
 * operation is a cryptographic provider-signature check (Stripe
 * signature/STRIPE_WEBHOOK_SECRET, per SRS v2.0 FR-SYS-007/NFR-SEC-011),
 * not a human session or an RBAC permission. Recorded explicitly so this
 * PUBLIC-at-the-guard-layer route is never mistaken for an ordinary
 * anonymous-open endpoint -- its real protection lives in the handler.
 */
export type VerificationMode = "PROVIDER_SIGNATURE";

/**
 * Set only where API Contract v1.1 itself ties production readiness to an
 * open GAP (currently GAP-013, file upload policy) via a documented
 * runtime error code (409 FILE_POLICY_NOT_CONFIGURED). This is deliberately
 * independent from `classification`/`authorizationMode`: "implementation
 * is deferred" and "here is the authorization policy that will apply once
 * implemented" are different concerns, and this field only ever describes
 * the former.
 */
export type ImplementationStatus = "DEFERRED_GAP_013";

export interface ApiOperationAuthorization {
  readonly apiId: string;
  readonly method: string;
  readonly path: string;
  readonly requiresAuth: boolean;
  readonly classification: RouteClassification;
  readonly authorizationMode: AuthorizationMode;
  readonly permissionKey: PermissionKey | null;
  /**
   * Set (with more than 1 entry) only for the handful of operations where
   * API Contract v1.1 itself ties a single HTTP operation to more than one
   * RBAC permission key (e.g. depending on which field of the request
   * body changed). permissionKey above is the first of these; this array
   * is the authoritative full set. Null for the normal single-key case.
   */
  readonly additionalPermissionKeys: readonly PermissionKey[] | null;
  readonly roles: readonly Role[];
  readonly scope: readonly ScopeType[];
  readonly resourceContextRequired: boolean;
  readonly assignmentRequired: boolean;
  readonly authScopeRequired: boolean;
  readonly workflowValidationRequired: boolean;
  readonly auditRequired: boolean;
  readonly nonDisclosure: string | null;
  readonly verificationMode: VerificationMode | null;
  readonly implementationStatus: ImplementationStatus | null;
  /**
   * Free-text documentary citation for operations whose authorization
   * mechanics are more nuanced than the typed fields alone convey (dual
   * public/authenticated paths, delegated caller-domain permission,
   * provider-signature verification, etc). Null for the ordinary case.
   */
  readonly note: string | null;
}

